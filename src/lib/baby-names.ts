// Matches by name, Arabic, or part of the meaning; optionally one gender; letters are compared without accents or case.
const fold = (s: string) => s.normalize('NFKD').replace(/[̀-ًͯ-ٟ]/g, '').toLowerCase()
export function searchNames(query: string, gender: Gender | 'all' = 'all', onlyFavourites?: Set<string>): BabyName[] {
  const q = fold(query.trim())
  return NAMES.filter((n) => (gender === 'all' || n.gender === gender) && (!onlyFavourites || onlyFavourites.has(n.name)) && (!q || fold(`${n.name} ${n.ar} ${n.meaning} ${n.note ?? ''}`).includes(q)))
}
