// Writes src/lib/recite-quran.ts: the Arabic and English of the few Quran passages that are recited inside prayers and rituals,
// copied straight from the app's own Quran data so nothing is typed by hand. Run: node scripts/gen-recite-quran.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const read = (p) => JSON.parse(readFileSync(new URL(`../data/quran/${p}`, import.meta.url), 'utf8'))
const surahs = read('surahs.json')
const ar = read('arabic.json')
const en = read('tr-en.json')
const offset = (s) => surahs.slice(0, s - 1).reduce((n, x) => n + x.verses_count, 0)

// [id, surah, from, to]
const PASSAGES = [
  ['fatiha', 1, 1, 7],
  ['ikhlas', 112, 1, 4],
  ['falaq', 113, 1, 5],
  ['nas', 114, 1, 6],
  ['kafirun', 109, 1, 6],
  ['kursi', 2, 255, 255],
  ['baqarah-end', 2, 285, 286],
  ['travel-ayah', 43, 13, 14],
  ['rabbana-atina', 2, 201, 201],
  ['safa-marwa', 2, 158, 158],
  ['kawthar', 108, 1, 3],
  ['asr', 103, 1, 3],
]

const out = {}
for (const [id, s, from, to] of PASSAGES) {
  const rows = []
  for (let v = from; v <= to; v++) {
    const i = offset(s) + v - 1
    rows.push({ n: v, ar: ar[i][1], en: en[i] })
  }
  out[id] = { surah: s, from, to, verses: rows }
}
writeFileSync(
  new URL('../src/lib/recite-quran.ts', import.meta.url),
  `// Generated by scripts/gen-recite-quran.mjs from the app's Quran data. Do not edit by hand.\nexport type QuranPassage = { surah: number; from: number; to: number; verses: { n: number; ar: string; en: string }[] }\nexport const QURAN_PASSAGES: Record<string, QuranPassage> = ${JSON.stringify(out, null, 1)}\n`
)
console.log('wrote', Object.keys(out).length, 'passages')
